def annotate_file(filepath):
    """为单个 .vue 文件添加注释"""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    original = content

    rel_path = os.path.relpath(filepath, BASE)

    # 1. 添加文件级 JSDoc 注释块
    file_header = FILE_COMMENTS.get(rel_path)
    if file_header and not content.lstrip().startswith('<!--'):
        content = file_header + '\n' + content

    # 2. 添加 script 块内部分隔注释
    script_markers = [
        ("// 状态", ["const", "let ", "ref(", "reactive(", "computed("]),
        ("// 数据加载", ["async function load", "function load"]),
        ("// 交互处理", ["function handle", "function toggle", "function on"]),
        ("// 表单提交", ["function save", "function submit"]),
        ("// 生命周期", ["onMounted(", "onShow(", "onLoad("]),
        ("// 导航", ["function go", "navigateTo", "router.push"]),
    ]

    for section_name, markers in script_markers:
        for marker in markers:
            # 查找第一个匹配的标记
            idx = content.find(marker)
            if idx > 0:
                # 检查前面是否已有注释
                lines_before = content[:idx].split('\n')
                last_line = lines_before[-1].strip()
                if not last_line.startswith('//'):
                    # 找到上一个空行
                    last_newline = content.rfind('\n\n', 0, idx)
                    if last_newline == -1:
                        last_newline = content.rfind('\n', 0, idx)
                    comment = f"\n// ============================================================================\n// {section_name}\n// ============================================================================\n"
                    content = content[:last_newline+1] + comment + content[last_newline+1:]
                break

    # Write only if changed
    if content != original:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"  [OK] Annotated: {rel_path}")
        return True
    else:
        print(f"  [--] No changes: {rel_path}")
        return False


def main():
    dirs_to_scan = [
        os.path.join(BASE, "views"),
        os.path.join(BASE, "components"),
    ]

    total = 0
    annotated = 0

    for scan_dir in dirs_to_scan:
        if not os.path.isdir(scan_dir):
            print(f"  [SKIP] Directory not found: {scan_dir}")
            continue
        print(f"\nScanning: {scan_dir}")
        for filepath in glob.glob(os.path.join(scan_dir, "**", "*.vue"), recursive=True):
            total += 1
            if annotate_file(filepath):
                annotated += 1

    print(f"\n========================================")
    print(f"完成！")
    print(f"总计: {total} 个文件")
    print(f"已注释: {annotated} 个文件")
    print(f"无变化: {total - annotated} 个文件")
    print(f"========================================")


if __name__ == "__main__":
    main()