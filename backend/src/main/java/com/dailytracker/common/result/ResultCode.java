package com.dailytracker.common.result;

import lombok.Getter;

/**
 * 统一响应状态码枚举 - 定义系统中所有可能的错误码和对应的消息
 *
 * 【类的用途】
 * 将所有的错误码和错误消息集中定义在一个枚举类中，作为系统错误码的唯一来源（Single Source of Truth）。
 * 配合 Result 类和 BusinessException 使用，实现统一的错误处理。
 *
 * 【设计思想】
 * 1. 使用枚举（enum）而非常量类：枚举天然是单例的、类型安全的、不可变的
 * 2. 按模块分段编号：便于定位错误所属模块
 *    - 通用错误码：200~599（与 HTTP 状态码对齐）
 *    - 用户模块：1001~1999
 *    - 计划模块：2001~2999
 *    - 记账模块：3001~3999
 *    - 摘录模块：4001~4999
 *    - 目标模块：5001~5999
 *    - 总结模块：6001~6999
 * 3. 消息面向用户：错误消息应该让终端用户能理解，而非技术术语
 *
 * 【在架构中的位置】
 * 属于通用层，被 Result、BusinessException、GlobalExceptionHandler 等广泛引用。
 *
 * 【扩展说明 - 错误码设计最佳实践】
 * 1. 错误码应保持稳定，发布后不应随意修改
 * 2. 新增错误码追加在模块段的末尾，不要复用已删除的错误码
 * 3. 错误码 + 消息可以作为前后端的"接口契约"
 *
 * @Getter Lombok 注解，自动生成 getCode() 和 getMessage() 方法
 */
@Getter
public enum ResultCode {

    // =================== 通用错误码（与 HTTP 状态码对齐） ===================

    /**
     * 操作成功 - HTTP 200
     */
    SUCCESS(200, "操作成功"),

    /**
     * 请求参数错误 - HTTP 400
     * 触发场景：@Valid 校验失败、参数格式不正确
     */
    BAD_REQUEST(400, "请求参数错误"),

    /**
     * 未认证 - HTTP 401
     * 触发场景：未登录就访问受保护资源、Token 过期
     */
    UNAUTHORIZED(401, "未认证，请先登录"),

    /**
     * 无权限 - HTTP 403
     * 触发场景：已登录但访问了无权限的资源
     */
    FORBIDDEN(403, "无权限访问"),

    /**
     * 资源不存在 - HTTP 404
     * 触发场景：查询的记录在数据库中不存在
     */
    NOT_FOUND(404, "资源不存在"),

    /**
     * 数据冲突 - HTTP 409
     * 触发场景：违反唯一约束（如重复注册）
     */
    CONFLICT(409, "数据已存在"),

    /**
     * 服务器内部错误 - HTTP 500
     * 触发场景：未预期的系统异常（兜底错误码）
     */
    INTERNAL_ERROR(500, "服务器内部错误"),

    // =================== 用户模块 1001~1999 ===================

    /**
     * 用户不存在 - 查询用户时未找到对应记录
     */
    USER_NOT_FOUND(1001, "用户不存在"),

    /**
     * 用户名已被占用 - 注册时用户名重复
     */
    USER_ALREADY_EXISTS(1002, "用户名已被占用"),

    /**
     * 用户名或密码错误 - 登录时凭证验证失败
     * 【安全注意】不区分"用户名不存在"和"密码错误"，防止攻击者枚举用户名
     */
    USER_PASSWORD_ERROR(1003, "用户名或密码错误"),

    /**
     * 账号已被禁用 - 管理员禁用了该账号
     */
    USER_DISABLED(1004, "账号已被禁用"),

    /**
     * Token 已过期 - JWT Token 超过有效期
     * 前端应使用 Refresh Token 获取新的 Access Token
     */
    USER_TOKEN_EXPIRED(1005, "Token已过期，请重新登录"),

    /**
     * Token 无效 - JWT Token 格式错误或签名不匹配
     */
    USER_TOKEN_INVALID(1006, "Token无效"),

    /**
     * 原密码错误 - 修改密码时输入的旧密码不正确
     */
    USER_OLD_PASSWORD_ERROR(1007, "原密码错误"),

    /**
     * 登录失败 - 其他登录异常的兜底错误码
     */
    USER_LOGIN_ERROR(1008, "登录失败"),

    // =================== 计划模块 2001~2999 ===================

    /**
     * 计划不存在 - 查询或操作的计划 ID 不存在
     */
    PLAN_NOT_FOUND(2001, "计划不存在"),

    /**
     * 计划日期无效 - 创建计划时指定了不合法的日期
     */
    PLAN_DATE_INVALID(2002, "计划日期无效"),

    // =================== 记账模块 3001~3999 ===================

    /**
     * 账目不存在 - 查询或操作的记账记录不存在
     */
    ACCOUNTING_NOT_FOUND(3001, "账目不存在"),

    /**
     * 记账分类不存在 - 引用了不存在的记账分类
     */
    ACCOUNTING_CATEGORY_NOT_FOUND(3002, "记账分类不存在"),

    /**
     * 预算已存在 - 尝试为已设置预算的月份重复设置预算
     */
    BUDGET_ALREADY_EXISTS(3003, "该月预算已设置"),

    // =================== 摘录模块 4001~4999 ===================

    /**
     * 摘录不存在 - 查询或操作的摘录记录不存在
     */
    EXCERPT_NOT_FOUND(4001, "摘录不存在"),

    // =================== 目标模块 5001~5999 ===================

    /**
     * 目标不存在 - 查询或操作的目标不存在
     */
    GOAL_NOT_FOUND(5001, "目标不存在"),

    /**
     * 父目标不存在 - 创建子目标时指定的父目标不存在
     */
    GOAL_PARENT_NOT_FOUND(5002, "父目标不存在"),

    /**
     * 目标循环引用 - 尝试将目标设置为其子目标的子目标，形成循环
     */
    GOAL_CIRCULAR_REFERENCE(5003, "不能将目标设置为其子目标的子目标"),

    // =================== 总结模块 6001~6999 ===================

    /**
     * 总结不存在 - 查询的每日总结不存在
     */
    SUMMARY_NOT_FOUND(6001, "总结不存在"),

    /**
     * 今日总结已存在 - 尝试创建总结时，今天的总结已经存在
     */
    SUMMARY_ALREADY_EXISTS(6002, "今日总结已存在");

    /**
     * 错误码 - 整数值，对应 Result 中的 code 字段
     */
    private final int code;

    /**
     * 错误消息 - 面向用户的文字描述，对应 Result 中的 message 字段
     */
    private final String message;

    /**
     * 枚举构造函数 - 每个枚举常量在声明时必须传入 code 和 message
     *
     * 【枚举构造函数特点】
     * - 枚举的构造函数默认是 private 的（只能在此枚举类内部调用）
     * - 在枚举常量声明时自动调用，如 SUCCESS(200, "操作成功")
     *
     * @param code    错误码
     * @param message 错误消息
     */
    ResultCode(int code, String message) {
        this.code = code;
        this.message = message;
    }
}
